-- The planned grid, as it exists in production since the start (written down later, safe to run again).
-- Access is still open to everyone; supabase/pending/enforce_grid_access.sql closes it.
create table if not exists public.images (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    url text,
    "order" bigint default '-1'::bigint,
    user_id text
);

alter table public.images enable row level security;

drop policy if exists "Allow all access" on public.images;
create policy "Allow all access" on public.images for all using (true) with check (true);

insert into storage.buckets (id, name, public)
values ('images', 'images', true)
on conflict (id) do nothing;

drop policy if exists "Give anon users access to JPG images in folder 1ffg0oo_0" on storage.objects;
drop policy if exists "Give anon users access to JPG images in folder 1ffg0oo_1" on storage.objects;
drop policy if exists "Give anon users access to JPG images in folder 1ffg0oo_2" on storage.objects;
drop policy if exists "Give anon users access to JPG images in folder 1ffg0oo_3" on storage.objects;
create policy "Give anon users access to JPG images in folder 1ffg0oo_0" on storage.objects
    for select using (bucket_id = 'images');
create policy "Give anon users access to JPG images in folder 1ffg0oo_1" on storage.objects
    for insert with check (bucket_id = 'images');
create policy "Give anon users access to JPG images in folder 1ffg0oo_2" on storage.objects
    for update using (bucket_id = 'images');
create policy "Give anon users access to JPG images in folder 1ffg0oo_3" on storage.objects
    for delete using (bucket_id = 'images');
